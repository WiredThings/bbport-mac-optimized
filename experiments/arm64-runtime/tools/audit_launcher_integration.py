#!/usr/bin/env python3
"""Read only original launcher/source inventory. Never starts a game or reads saves/tokens."""
from pathlib import Path
import argparse,difflib,hashlib,json,re,time
P=Path('/Users/Shared/BloodEchoesDevelopment/arm64-runtime-prototype')
R=Path('/Users/k.d./Documents/Codex/2026-10-16/https-github-com-loreanxavier-pt-pc/work/bbport-mac-optimized')
parser=argparse.ArgumentParser();parser.add_argument('--imports',type=Path);options=parser.parse_args()
def digest(p): return hashlib.sha256(p.read_bytes()).hexdigest()
def diff(a,b): return ''.join(difflib.unified_diff(a.read_text(errors='replace').splitlines(True),b.read_text(errors='replace').splitlines(True),fromfile=str(a),tofile=str(b),n=2))
e=P/'evidence'/('launcher-source-inventory-'+str(time.time_ns()));e.mkdir()
gui=[]
for a in sorted((R/'launcher-macos').rglob('*')):
 if not a.is_file()or a.suffix not in ('.swift','.strings')or'.build'in a.parts: continue
 rel=a.relative_to(R/'launcher-macos');b=P/'launcher-gui-source'/rel
 row=dict(path=str(rel),present=b.is_file(),same=b.is_file()and digest(a)==digest(b))
 if b.is_file(): row.update(original_sha256=digest(a),qa_sha256=digest(b))
 if b.is_file()and not row['same']:row['diff']=diff(a,b)
 gui.append(row)
scripts=[]
for rel in json.loads((P/'launcher-component-stage/SOURCE-PARITY.json').read_text())['original_sources']:
 a=R/rel;b=P/'launcher-component-stage'/rel
 scripts.append(dict(path=rel,same=a.is_file()and b.is_file()and digest(a)==digest(b)))
runtime=[]
for a in sorted((R/'src').glob('*')):
 b=P/'vendor/bb_runtime/src'/a.name
 if a.is_file()and b.is_file()and a.suffix in ('.c','.h'):
  row=dict(path=a.name,same=digest(a)==digest(b),original_sha256=digest(a),qa_sha256=digest(b))
  if not row['same']:row['diff']=diff(a,b)
  runtime.append(row)
flags=set(re.findall(r'id: "(BB_[A-Z0-9_]+)"',(R/'launcher-macos/Sources/BBLauncher/MetalOptimizations.swift').read_text()))
consumers={k:[]for k in flags}
paths=list((P/'vendor/metal_api').rglob('*'))+list((P/'src').glob('*'))+list((P/'vendor/bb_runtime/src').glob('*'))+list((P/'launcher-component-stage/scripts').glob('*.py'))+[P/'launcher-component-stage/tools/macos/run_optimized.sh']
for f in paths:
 if not f.is_file()or f.suffix not in('.cpp','.h','.mm','.c','.py','.sh'):continue
 for n,line in enumerate(f.read_text(errors='replace').splitlines(),1):
  for key in flags:
   if '"'+key+'"'in line or '${'+key in line or re.search(r'\b'+key+r'=',line):
    if len(consumers[key])<5:consumers[key].append(str(f.relative_to(P))+':'+str(n))
signatures=json.loads((P/'generated/native-signatures.json').read_text())
result=dict(schema=1,scope='source audit only; no live game, save, preference or credential access',gui=gui,scripts=scripts,runtime=runtime,metal_options=consumers,native_bridge_functions=len(signatures),unsupported_native_signatures=[x for x in signatures if'unsupported'in x],all_launch_scripts_identical=all(x['same']for x in scripts))
(e/'inventory.json').write_text(json.dumps(result,indent=2)+'\n')
(e/'source-differences.patch').write_text('\n'.join(x['diff']for x in gui+runtime if'diff'in x))
summary=dict(evidence=str(e),gui_files=len(gui),gui_identical=sum(x['same']for x in gui),gui_missing=[x['path']for x in gui if not x['present']],scripts=len(scripts),scripts_identical=sum(x['same']for x in scripts),runtime_files=len(runtime),runtime_identical=sum(x['same']for x in runtime),metal_options=len(flags),metal_options_without_text_consumer=[k for k,v in consumers.items()if not v],native_bridge_functions=len(signatures),unsupported=len(result['unsupported_native_signatures']))
# Existing required import metadata is generated by the real original-launcher
# QA session. It contains symbol names/routes only, not save data or credentials.
required=options.imports or P/'state/gui-user-1792838936841921000/imports.tsv'
if options.imports is not None:
 required=required.absolute()
 assert required==required.resolve() and required.is_relative_to(P/'state') and required.name=='imports.tsv' and required.is_file(),'explicit private QA import metadata required'
summary['required_import_metadata_historical_default']=options.imports is None
summary['required_import_metadata_sha256']=digest(required) if required.is_file() else None
imports=[]
if required.exists():
 for line in required.read_text().splitlines():
  row=line.split('\t')
  if len(row)>=4:imports.append(dict(index=int(row[0]),name=row[1],route=row[2],nid=row[3]))
unresolved=[x for x in imports if x['route'].startswith('missing')]
av_impl=(P/'vendor/metal_api/shadps4/core/libraries/avplayer/avplayer.cpp').read_text()
host_functions=set(re.findall(r'LIB_FUNCTION\([^;]*,\s*(sceAvPlayer\w+)\);',av_impl))
for item in unresolved:item['original_AV_implementation_present']=item['name']in host_functions
summary.update(provided_signature_unsupported=summary['unsupported'],required_imports=len(imports),required_imports_unresolved=len(unresolved),required_import_coverage_complete=bool(imports)and not unresolved,original_AV_implementation_without_adapter=[x['name']for x in unresolved if x['original_AV_implementation_present']],inventory_is_not_full_runtime_acceptance=True)
(e/'required-imports.json').write_text(json.dumps(dict(source=str(required),rows=imports,unresolved=unresolved),indent=2)+'\n')
(e/'summary.json').write_text(json.dumps(summary,indent=2)+'\n')
print(json.dumps(summary,indent=2))
