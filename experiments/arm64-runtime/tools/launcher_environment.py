#!/usr/bin/env python3
"""Private read-only source snapshots of the launcher's shared Metal policy."""
from pathlib import Path
import json,re
P=Path(__file__).resolve().parents[1]
PREFIX=('BB_MTL_','BB_TEXTURE_','BB_GPU_WRITE_')
EXACT={'BB_PC_MODEL','BB_GUEST_IN_PLACE','BB_LAYER_MEMORY','BB_GUEST_MEMORY','BB_GPU_LIFETIME','BB_PREUPLOAD','BB_UFFD','BB_COPY_GPU_BUFFERS','BB_AUTO_NOHIZ','BB_GPU_LABELS','BB_HDR','BB_SKIP_EMPTY_DRAWS','BB_VK_RECORD_THREADS','BB_FRAMES_AHEAD','BB_GPU_QOS','BB_PIPE_PARK_WAITS','BB_CMDBUF_TRIM','BB_KK_POOL_FIX'}
def shell_defaults(text):
 result={}
 for line in text.splitlines():
  if not line.lstrip().startswith('export '):continue
  for m in re.finditer(r'\b([A-Z][A-Z0-9_]*)=(\$\{([A-Z][A-Z0-9_]*):-([a-zA-Z0-9_-]+)\}|[a-zA-Z0-9_-]+)(?=\s|$)',line):
   key,value,parent,default=m.groups()
   if key.startswith(PREFIX) or key in EXACT:
    if parent and parent!=key:raise ValueError('unexpected inherited variable '+key)
    result.setdefault(key,default if parent else value)
 if result.get('BB_FRAMES_AHEAD')!='2' or result.get('BB_MTL_BATCH_CLEARS')!='1':raise ValueError('launcher environment policy missing')
 return result

def load(strict=True):
 defaults=shell_defaults((P/'vendor/blood_echoes/run_optimized.sh').read_text())
 # Generated by the unchanged Swift MetalOptimizations.environment implementation.
 shared=json.loads((P/'fixtures/launcher-metal-environment.json').read_text())
 assert all(re.fullmatch(r'BB_[A-Z0-9_]+',k) and v in ('0','1') for k,v in shared.items())
 defaults.update(shared)
 if strict:
  # Same two explicit constraints for both private engines. No formal preference write.
  # Retain current ARM prototype V1 Safe math and avoid archive's additional residency.
  defaults.update(BB_MTL_PERSIST_WARM_ARCHIVE='0',BB_MTL_RELAXED_MATH='0',BB_MTL_STRICT_FLOAT='0')
 return defaults
if __name__=='__main__':print(json.dumps(load(),indent=2,sort_keys=True))
